#!/usr/bin/env bash
# Rebuild the path-scoped rules files from the personal code-style guides.
# Each rules file is a paths: header plus the full guide text. The text is copied, not @-imported:
# an @-import in a rules file loads at session start and ignores paths:.
# Usage: sync-rules.sh
set -euo pipefail

GUIDE_DIR="${CODE_STYLE_GUIDE_DIR:-${HOME}/.claude/memory/guidelines}"
RULES_DIR="${CODE_STYLE_RULES_DIR:-${HOME}/.claude/rules}"
MARKER="<!-- generated by code-preference-skill scripts/sync-rules.sh"

# Print the paths: globs for one guide language, one per line.
# Arguments: the language, taken from the guide file name.
lang_paths() {
    local lang="${1}"
    case "${lang}" in
        # for code-style-python.md
        python) printf '%s\n' '**/*.py' '**/*.ipynb' '**/pyproject.toml' ;;
        # for code-style-bash.md
        bash) printf '%s\n' '**/*.sh' '**/*.bash' '**/.shellcheckrc' ;;
        *)
            echo "Error: no paths: list for guide language '${lang}'; add one to sync-rules.sh" >&2
            return 1
            ;;
    esac
}

# Print the rules file for one guide.
# Arguments: the guide path, its globs (one per line).
render() {
    local guide="${1}" globs="${2}"
    local glob
    echo "---"
    echo "paths:"
    while IFS= read -r glob; do
        echo "  - \"${glob}\""
    done <<<"${globs}"
    echo "---"
    echo
    echo "${MARKER} from ${guide}. Do not edit; edit the guide. -->"
    echo
    cat -- "${guide}"
}

main() {
    mkdir -p "${RULES_DIR}"
    local guides=() failed=()
    shopt -s nullglob
    guides=("${GUIDE_DIR}"/code-style-*.md)
    shopt -u nullglob

    local guide lang globs target content
    # bash 3.2 treats "${guides[@]}" of an empty array as unbound under set -u
    if ((${#guides[@]} > 0)); then
        for guide in "${guides[@]}"; do
            lang="$(basename "${guide}" .md)"
            lang="${lang#code-style-}"
            if ! globs="$(lang_paths "${lang}")"; then
                failed+=("${lang}")
                continue
            fi
            target="${RULES_DIR}/code-style-${lang}.md"
            content="$(render "${guide}" "${globs}")"
            if [[ -f "${target}" && "$(cat -- "${target}")" == "${content}" ]]; then
                continue
            fi
            printf '%s\n' "${content}" >"${target}"
            echo "code-style rules: refreshed ${target}"
        done
    fi

    # remove generated copies whose guide is gone; leave hand-written files alone
    local rules=()
    shopt -s nullglob
    rules=("${RULES_DIR}"/code-style-*.md)
    shopt -u nullglob
    if ((${#rules[@]} > 0)); then
        for target in "${rules[@]}"; do
            if [[ ! -e "${GUIDE_DIR}/$(basename "${target}")" ]] && grep -q -F -- "${MARKER}" "${target}"; then
                rm -f -- "${target}"
                echo "code-style rules: removed ${target} (guide gone)"
            fi
        done
    fi

    if ((${#failed[@]} > 0)); then
        echo "Error: code-style rules not synced for: ${failed[*]}" >&2
        exit 1
    fi
}

main "$@"
